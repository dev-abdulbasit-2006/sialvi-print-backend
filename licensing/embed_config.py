"""Bake the CLOUD licensing server address + its PUBLIC key into the Admin/User apps (shared/license_embedded.py).

Licensing is cloud-only (Render). There is no local / LAN / plain-HTTP mode.

  python licensing/embed_config.py --fetch                 download the public key from the cloud server and write the file
  python licensing/embed_config.py --public-key-file k.pem write the file from a key you already have
  python licensing/embed_config.py --check                 offline check of the embedded file (used by the build scripts)
  python licensing/embed_config.py --check --online        also contact the cloud server and compare its live key (RELEASE builds)

Run it BEFORE building the installers. Verify the printed key fingerprint against the Owner License Manager
(App Builds tab) so you know the key really came from YOUR server.
"""
import argparse
import hashlib
import ipaddress
import sys
import time
from pathlib import Path
from urllib.parse import urlparse

# Run as a script by the build (python licensing\\embed_config.py): the project root must be importable.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from shared.cloud_config import CLOUD_LICENSE_URL  # noqa: E402

TARGET = Path(__file__).resolve().parent.parent / "shared" / "license_embedded.py"

TEMPLATE = '''"""Build-time licensing settings baked into the Admin and User apps (cloud licensing on Render).

GENERATED by licensing/embed_config.py (or the Owner License Manager > App Builds tab) BEFORE building.
They are compiled into the .exe on purpose: a customer must not be able to point the app at a fake
licensing server. Only the PUBLIC key is stored - it can verify tokens, never create them.
"""
SERVER_URL = {url!r}
LICENSE_SERVER_URL = SERVER_URL        # alias for code that uses the longer name
PUBLIC_KEY_PEM = {pem!r}
'''


def fingerprint(pem: str) -> str:
    return hashlib.sha256(pem.strip().encode("ascii")).hexdigest()[:32]


def _check_cloud_host(host: str):
    """Reject anything that is not a real internet host name: localhost, LAN/private/loopback IPs, .local names."""
    h = (host or "").lower().strip(".")
    if not h:
        raise ValueError("The licensing server address has no host name.")
    try:
        ipaddress.ip_address(h.strip("[]"))
        is_ip = True
    except ValueError:
        is_ip = False
    if is_ip:
        raise ValueError("The licensing server must be a public host NAME (like sialvi-print-backend.onrender.com), "
                         "not an IP address. Local / LAN licensing servers are not supported.")
    if h == "localhost" or "." not in h or h.endswith((".local", ".lan", ".internal", ".localdomain", ".home")):
        raise ValueError("Local licensing servers are not supported: use the cloud server's public https:// address.")


def validate(server_url: str, pem: str) -> str:
    server_url = (server_url or "").strip().rstrip("/")
    p = urlparse(server_url)
    if p.scheme != "https":
        raise ValueError("The licensing server address must start with https:// (customers' PCs talk to it over the internet).")
    _check_cloud_host(p.hostname)
    from shared.license_client import validate_public_key_pem
    if "BEGIN PUBLIC KEY" not in (pem or ""):
        raise ValueError("No licensing public key is embedded yet (expected a PEM 'BEGIN PUBLIC KEY' block).")
    validate_public_key_pem(pem)            # must be Ed25519 (the server's signature scheme), not RSA
    return server_url


def write_embedded(server_url: str, pem: str, target: Path = TARGET) -> Path:
    server_url = validate(server_url, pem)
    Path(target).write_text(TEMPLATE.format(url=server_url, pem=pem.strip() + "\n"), encoding="utf-8")
    return Path(target)


def _get_json(url: str, timeout: float):
    import requests
    r = requests.get(url, timeout=timeout)          # certificate validation stays ON
    r.raise_for_status()
    return r.json()


def fetch_public_key(server_url: str, timeout: float = 60, attempts: int = 4, pause: float = 5) -> str:
    """Download the server's public key. The free Render tier sleeps when idle and needs ~30-60 s to wake,
    so the first requests may time out: retry a few times before giving up."""
    base = server_url.rstrip("/")
    last = None
    for i in range(attempts):
        try:
            _get_json(base + "/api/v1/health", timeout)                 # wakes the service up
            return _get_json(base + "/api/v1/public-key", timeout)["public_key"]
        except Exception as exc:                                       # noqa: BLE001
            last = exc
            if i + 1 < attempts:
                time.sleep(pause)
    raise RuntimeError(f"Could not reach the licensing server {base} ({type(last).__name__}: {last}). "
                       "Check the internet connection and that the Render service is deployed.")


def check(target: Path = TARGET, online: bool = False) -> tuple[bool, str]:
    ns = {}
    try:
        exec(compile(Path(target).read_text(encoding="utf-8"), str(target), "exec"), ns)
        url = validate(ns.get("SERVER_URL", ""), ns.get("PUBLIC_KEY_PEM", ""))
    except Exception as exc:
        return False, str(exc) or "shared/license_embedded.py is empty."
    pem = ns["PUBLIC_KEY_PEM"]
    msg = f"Licensing configured: {url} (key {fingerprint(pem)})"
    if online:
        try:
            live = fetch_public_key(url)
        except Exception as exc:
            return False, f"{exc}\nThe release build verifies the embedded key against the live cloud server and cannot continue."
        if live.strip() != pem.strip():
            return False, (f"The public key embedded in the apps ({fingerprint(pem)}) does NOT match the live server's key "
                           f"({fingerprint(live)}). Apps built like this could never activate. "
                           "Run: python licensing\\embed_config.py --fetch")
        msg += "\n  Verified online: the cloud server's key matches the embedded key."
    return True, msg


def main(argv=None):
    sys.path.insert(0, str(TARGET.parent.parent))
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--server", default=CLOUD_LICENSE_URL, help=f"default: {CLOUD_LICENSE_URL}")
    ap.add_argument("--public-key-file")
    ap.add_argument("--fetch", action="store_true", help="download the public key from the cloud server (verify the fingerprint!)")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--online", action="store_true", help="with --check: also compare against the live cloud server")
    a = ap.parse_args(argv)
    if a.check:
        ok, msg = check(online=a.online)
        print(msg if ok else "LICENSING NOT READY: " + msg + "\nFix: python licensing\\embed_config.py --fetch")
        sys.exit(0 if ok else 1)
    if not (a.fetch or a.public_key_file):
        ap.error("use --fetch (download from the cloud server) or --public-key-file")
    try:
        pem = fetch_public_key(a.server) if a.fetch else Path(a.public_key_file).read_text()
        path = write_embedded(a.server, pem)
    except (ValueError, RuntimeError, OSError) as exc:
        sys.exit(f"ERROR: {exc}")
    print(f"Wrote {path}\nServer: {a.server}\nPublic key fingerprint: {fingerprint(pem)}\n"
          "Compare it with the Owner License Manager > App Builds tab.")


if __name__ == "__main__":
    main()
